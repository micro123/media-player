@Composable
fun PlayerSymbol(symbol: PlayerIcon, modifier: Modifier = Modifier, description: String? = null) {
    val vector = remember(symbol) {
        ImageVector.Builder(symbol.name, 24.dp, 24.dp, 24f, 24f).apply {
            addPath(PathParser().parsePathString(symbol.path).toNodes(), fill = SolidColor(Color.White))
        }.build()
    }
    Icon(imageVector = vector, contentDescription = description, modifier = modifier)
}
